// 暮らしから見た満足度（0〜100）：政情・治安・食べもの・水・貧富の差から。国民の気持ちは毎年これに少し寄っていく
export function livingMood(c) {
  const s = c.stats;
  const food = Math.min(120, s.food) / 1.2;
  return Math.round(0.3 * s.stability + 0.2 * s.security + 0.15 * food + 0.15 * s.water + 0.2 * (100 - s.inequality));
}
