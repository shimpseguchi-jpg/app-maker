const SCOPE_KID = { self: 'じぶん', tgt: 'あいて', all: 'ほかの くに', nb: 'となりの くに', tgtNb: 'あいての となり', bgAll: 'ちいさな くに', poorBg: 'まずしい くに', majors: 'みんな', world: 'せかい' };
export function kidFx(list) {
  const groups = {};
  for (const raw of list || []) {
    if (raw === 'ally') { (groups['あいて'] ||= {}).friend = 1; continue; }
    if (raw === 'nuke+') { (groups['じぶん'] ||= {}).army = 2; continue; }
    const m = /^(\w+)\.(\w+)([+-])([sml])$/.exec(raw);
    if (!m) continue;
    const [, scope, stat, sg] = m;
    let key, bad = false, who;
    if (scope === 'rel') { who = stat === 'tgt' ? 'あいて' : 'ほかの くに'; key = 'friend'; }
    else if (scope === 'world') { const w = KID_WORLD[stat]; if (!w) continue; [key, bad] = w; who = 'せかい'; }
    else { key = KID_STAT_OF[stat]; if (!key) continue; bad = KID_BAD.has(stat); who = SCOPE_KID[scope] || 'あいて'; }
    const v = (sg === '+') !== bad ? 1 : -1;
    const g = (groups[who] ||= {});
    g[key] = (g[key] || 0) + v;
  }
  return Object.entries(groups).map(([who, ks]) => `${who} ${Object.entries(ks).filter(([, v]) => v).map(([k, v]) => KID_ICON[k] + (v > 0 ? '↑' : '↓')).join(' ')}`).filter((x) => /[↑↓]/.test(x));
}
