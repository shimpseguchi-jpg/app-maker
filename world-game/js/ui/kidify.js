const DICT = { ...Object.fromEntries(KATA.map((w) => [w, toKata(w)])), ...KANJI };
const KEYS = Object.keys(DICT).sort((a, b) => b.length - a.length);
const RE = new RegExp(`(?<![ぁ-ゖァ-ヺー々一-龯])(?:${KEYS.join('|')})`, 'g');

function toKata(s) { return s.replace(/[ぁ-ゖ]/g, (c) => String.fromCharCode(c.charCodeAt(0) + 0x60)); }

export function kidify(s) {
  if (!s || !/[ぁ-ゖ]/.test(s)) return s;
  return s.replace(RE, (w) => DICT[w]);
}

export const KIDIFY_DICT = DICT;

// 画面の文字を見はって、1ねんせいモードのときだけ置きかえる
export function watchKid(root, isKid) {
  const fixNode = (n) => {
    if (n.nodeType === 3) {
      const t = kidify(n.data);
      if (t !== n.data) n.data = t;
    } else if (n.nodeType === 1) {
      if (n.tagName === 'SCRIPT' || n.tagName === 'STYLE') return;
      for (const a of ['title', 'placeholder', 'aria-label']) {
        const v = n.getAttribute(a);
        if (v) { const t = kidify(v); if (t !== v) n.setAttribute(a, t); }
      }
      for (const c of n.childNodes) fixNode(c);
    }
  };
  const obs = new MutationObserver((list) => {
    if (!isKid()) return;
    for (const m of list) {
      if (m.type === 'characterData') fixNode(m.target);
      else for (const n of m.addedNodes) fixNode(n);
    }
  });
  obs.observe(root, { childList: true, subtree: true, characterData: true });
  return () => { if (isKid()) fixNode(root); };
}
