// こくごの もんだい（データしき ＋ せいせいしき）。かんじは モードに かかわらず そのまま だす
const pick = (rng, a) => a[Math.floor(rng() * a.length)];
const shuffle = (rng, a) => { a = [...a]; for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rng() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; };

