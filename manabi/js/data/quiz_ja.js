export const QUIZ_JA = {
  kanjiRead(g, rng) {
    const list = KANJI[Math.min(3, g)];
    const k = pick(rng, list);
    const others = shuffle(rng, list.filter((x) => x[1] !== k[1])).slice(0, 2).map((x) => x[1]);
    return { q: `「${k[2]}」の <b>${k[0]}</b> の よみかたは？`, answer: k[1], choices: shuffle(rng, [k[1], ...others]), explain: `${k[0]} は「${k[1]}」と よむよ。「${k[2]}」`, unit: 'kanji' };
  },
  kanjiPick(g, rng) {
    const list = KANJI[Math.min(3, g)];
    const k = pick(rng, list);
    const others = shuffle(rng, list.filter((x) => x[0] !== k[0])).slice(0, 2).map((x) => x[0]);
    const sentence = k[2].replace(k[0], '□');
    return { q: `「${sentence}」の □に はいる かんじは？（${k[1]}）`, answer: k[0], choices: shuffle(rng, [k[0], ...others]), explain: `「${k[2]}」。${k[1]} は ${k[0]} と かくよ`, unit: 'kanji' };
  },
  antonym(g, rng) {
    const pr = pick(rng, ANTONYM); const flip = rng() < 0.5;
    const [a, b] = flip ? [pr[1], pr[0]] : pr;
    const others = shuffle(rng, ANTONYM.filter((x) => x !== pr)).slice(0, 2).map((x) => x[Math.floor(rng() * 2)]);
    return { q: `「${a}」の はんたいの ことばは？`, answer: b, choices: shuffle(rng, [b, ...others]), explain: `「${a}」の はんたいは「${b}」`, unit: 'antonym' };
  },
  katakana(g, rng) {
    const it = pick(rng, KATAKANA);
    const others = shuffle(rng, KATAKANA.filter((x) => x !== it)).slice(0, 2).map((x) => x[1]);
    return { q: `この えを カタカナで かくと？`, answer: it[1], choices: shuffle(rng, [it[1], ...others]), vis: { type: 'emoji', rows: [[it[0], 1]] }, explain: `${it[0]} は「${it[1]}」`, unit: 'katakana' };
  },
  oddOne(g, rng) {
    const grp = pick(rng, GROUPS); const other = pick(rng, GROUPS.filter((x) => x !== grp));
    const members = shuffle(rng, grp[1]).slice(0, 3); const odd = pick(rng, other[1]);
    return { q: `なかまはずれは どれ？`, answer: odd, choices: shuffle(rng, [...members, odd]), explain: `${members.join('・')} は「${grp[0]}」の なかま。${odd} は「${other[0]}」`, unit: 'group' };
  },
  particle(g, rng) {
    const it = pick(rng, PARTICLES);
    return { q: `［　］に はいるのは？　${it[0]}`, answer: it[1], choices: shuffle(rng, ['は', 'を', 'へ']), explain: `「${it[0].replace('［　］', it[1])}」`, unit: 'particle' };
  },
  order(g, rng) {
    const s = pick(rng, SENTENCES);
    const ans = s.join(' ');
    const wrongs = new Set();
    let guard = 0;
    while (wrongs.size < 2 && guard++ < 20) { const p = shuffle(rng, s).join(' '); if (p !== ans) wrongs.add(p); }
    return { q: `ただしい じゅんばんの ぶんは？`, answer: ans, choices: shuffle(rng, [ans, ...wrongs]), explain: `「${ans}」。だれが（なにが）→ なにを・どこで → どうする`, unit: 'order' };
  },
  kosoado(g, rng) {
    const it = pick(rng, KOSOADO);
    return { q: `${it[0]}に つかう ことばは？`, answer: it[1], choices: shuffle(rng, ['これ', 'それ', 'あれ', 'どれ']).slice(0, 4), explain: `${it[0]}は「${it[1]}」`, unit: 'kosoado' };
  },
};
// がくねん・レベルごとの だしかた（レベル 1〜8）
export function jaTopics(g, level) {
  if (g === 1) return level <= 3 ? ['katakana', 'oddOne', 'antonym'] : level <= 6 ? ['kanjiRead', 'particle', 'antonym', 'katakana'] : ['kanjiRead', 'kanjiPick', 'order', 'particle'];
  if (g === 2) return level <= 3 ? ['kanjiRead', 'antonym', 'oddOne'] : level <= 6 ? ['kanjiRead', 'kanjiPick', 'order', 'particle'] : ['kanjiPick', 'order', 'kanjiRead'];
  return level <= 3 ? ['kanjiRead', 'antonym', 'order'] : level <= 6 ? ['kanjiRead', 'kanjiPick', 'kosoado'] : ['kanjiPick', 'kosoado', 'order'];
}
