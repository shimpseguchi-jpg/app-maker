const EASY = ['flat', 'step1', 'gap2', 'enemy1', 'spike2', 'platform', 'flat'];
const MID = ['step1', 'gap3', 'stairs', 'gapSpike', 'twoEnemy', 'highroad', 'pillar', 'island', 'platform'];
const Q = ['qLow', 'qHigh', 'qEnemy'];

// term 1=ぜんき 2=こうき。rng は シードつき。かえりは { rows: string[], zones: [{subj, x0, x1}], blocks: [{x, y, subj, idx}] }
export function buildStage(term, rng, subjects = ['math', 'ja', 'en']) {
  const perZone = term === 1 ? 5 : 7; // ふつうの チャンクの かず（＋ もんだい 2）
  const pool = term === 1 ? EASY : [...EASY, ...MID, ...MID];
  const seq = [['start', null]];
  for (let z = 0; z < subjects.length; z++) {
    const subj = subjects[z];
    const names = [];
    let last = null;
    for (let i = 0; i < perZone; i++) {
      let n = rng.pick(pool); let guard = 0;
      // あなや トゲは つづけない
      // あな・トゲの つぎに あな・トゲは おかない。かいだんの つぎは ひらち（たかい ところから とびおりて あなに おちないように）
      while ((n === last || (/gap|Spike|highroad|island/.test(n) && /gap|Spike|highroad|island|stairs/.test(last || ''))) && guard++ < 20) n = rng.pick(pool);
      if (last === 'stairs' && /gap|Spike|highroad|island|stairs/.test(n)) n = 'flat';
      names.push(n); last = n;
    }
    // もんだいブロックを 2つ はさむ（はじめの ほうと なかほど）
    names.splice(1, 0, rng.pick(Q));
    names.splice(Math.floor(names.length / 2) + 1, 0, rng.pick(Q));
    for (const n of names) seq.push([n, subj]);
    seq.push([z === subjects.length - 1 ? 'goal' : 'check', subj]);
  }
  const rows = Array.from({ length: ROWS }, () => '');
  const zones = []; const blocks = [];
  let x = 0; let zoneStart = 12; let curSubj = null; let qIdx = 0;
  for (const [name, subj] of seq) {
    const ch = CHUNKS[name];
    if (subj !== curSubj && subj) { curSubj = subj; zoneStart = x; qIdx = 0; }
    for (let r = 0; r < ROWS; r++) {
      let line = ch[r];
      const qi = line.indexOf('?');
      if (qi >= 0) { blocks.push({ x: x + qi, y: r, subj, idx: qIdx++ }); }
      rows[r] += line;
    }
    x += 12;
    if (name === 'check' || name === 'goal') zones.push({ subj, x0: zoneStart, x1: x });
  }
  // ゴールの うしろに すこし じめんを つける
  for (let r = 0; r < ROWS; r++) rows[r] += r >= ROWS - 2 ? '########' : '........';
  return { rows, zones, blocks, width: rows[0].length, term };
}
